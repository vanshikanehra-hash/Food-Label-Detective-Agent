"""
Food Label Detective Agent - controller.

This is the "brain" that ties the pieces together into an agentic workflow:

    input -> understand task -> ask missing info -> use tools/memory
          -> analyse -> apply guardrails -> explain (LLM) -> log

The plain-English explanation is generated by an LLM (Claude) when an API key
is available. If no key is set, a deterministic template writer produces a
clear explanation instead, so the project runs fully offline out of the box.
"""

from __future__ import annotations

import json
import os

from . import off_client, preprocessing, guardrails, preferences as prefs_module
from .logger import log_run

# --- LLM configuration ------------------------------------------------------

# We default to the latest capable Claude model. Override with LLM_MODEL.
LLM_MODEL = os.environ.get("LLM_MODEL", "claude-sonnet-5")

SYSTEM_PROMPT = (
    "You are the Food Label Detective, a friendly assistant that explains "
    "packaged-food labels to everyday shoppers in plain, simple English. "
    "You are given structured analysis of a product (ingredients, allergens, "
    "additives, nutrition levels, a risk score, and how it matches the user's "
    "dietary preferences). Your job:\n"
    "1. Summarise what the product is in one sentence.\n"
    "2. Explain the key concerns in simple, non-alarming language.\n"
    "3. Clearly state how it fits (or clashes with) the user's preferences.\n"
    "4. Never give medical advice, never guarantee safety, and always remind "
    "the user to check the physical label for allergies.\n"
    "Keep it under 180 words. Use short sentences and, where helpful, bullet "
    "points. Do not invent facts that are not in the analysis."
)


def _llm_available() -> bool:
    return bool(os.environ.get("ANTHROPIC_API_KEY"))


def _explain_with_llm(context: dict) -> str | None:
    """Ask Claude to write the plain-English explanation. None on any failure."""
    try:
        import anthropic  # imported lazily so the package is optional
    except ImportError:
        return None

    try:
        client = anthropic.Anthropic()
        user_content = (
            "Here is the structured product analysis as JSON. Write the "
            "shopper-friendly explanation described in your instructions.\n\n"
            + json.dumps(context, ensure_ascii=False, indent=2)
        )
        message = client.messages.create(
            model=LLM_MODEL,
            max_tokens=600,
            system=SYSTEM_PROMPT,
            messages=[{"role": "user", "content": user_content}],
        )
        return "".join(
            block.text for block in message.content if getattr(block, "type", "") == "text"
        ).strip()
    except Exception:
        # Any API/network/auth error -> fall back to the template writer.
        return None


def _explain_with_template(context: dict) -> str:
    """Deterministic, offline plain-English explanation (LLM fallback)."""
    product = context["product"]
    analysis = context["analysis"]
    guard = context["guardrails"]

    lines = [f"**{product['product_name']}** "
             f"({product.get('brands') or 'brand unknown'})."]

    # What it is.
    if analysis["ingredients"]:
        top = ", ".join(analysis["ingredients"][:4])
        lines.append(f"Main ingredients: {top}.")

    # Nutrition in plain words.
    highs = [n["nutrient"] for n in analysis["nutrition"] if n["level"] == "high"]
    if highs:
        lines.append("Watch out — it is high in " + ", ".join(highs) + ".")
    else:
        lines.append("No nutrient is in the 'high' band based on available data.")

    # Additives.
    if analysis["additives"]:
        lines.append("Notable additives: " + "; ".join(analysis["additives"]) + ".")

    # Allergens.
    if analysis["allergens"]:
        lines.append("Possible allergens: " + ", ".join(analysis["allergens"]) + ".")

    # Preference fit.
    if guard["conflicts"]:
        lines.append("Regarding your preferences:")
        for c in guard["conflicts"]:
            lines.append(f"  - {c['message']}")
    else:
        lines.append("It does not clash with the preferences you set.")

    # Recommendation phrasing.
    rec_text = {
        "avoid": "Recommendation: best avoided given your settings.",
        "caution": "Recommendation: okay in moderation, but review the concerns above.",
        "ok_to_consider": "Recommendation: looks reasonable for your preferences.",
    }[guard["recommendation"]]
    lines.append(rec_text)

    return "\n".join(lines)


def _missing_info_questions(query: str, user_id: str) -> list[str]:
    """Agentic 'ask clarifying questions' step."""
    questions = []
    if not query or not query.strip():
        questions.append(
            "Which product should I check? Enter a barcode (e.g. 3017620422003) "
            "or a product name (e.g. 'Nutella')."
        )
    return questions


def analyse_product(query: str, user_id: str = "default") -> dict:
    """
    Run the full agent workflow for one product query.

    Returns a structured result dict. If required info is missing, the result
    contains `needs_input: True` and a list of questions instead of an analysis.
    """
    # Step 1-2: understand task & ask missing questions.
    questions = _missing_info_questions(query, user_id)
    if questions:
        return {"status": "needs_input", "needs_input": True, "questions": questions}

    # Step 3: load memory (preferences) and fetch product via tools.
    preferences = prefs_module.get_preferences(user_id)
    product = off_client.resolve_product(query)

    if product is None:
        result = {
            "status": "not_found",
            "query": query,
            "message": (
                f"I could not find a product matching '{query}'. Try a different "
                "barcode or name, or check the spelling."
            ),
            "preferences": preferences,
        }
        log_run({"user_id": user_id, "query": query, "status": "not_found"})
        return result

    # Step 4: deterministic analysis (tools/logic).
    analysis = preprocessing.build_label_analysis(product)

    # Step 5: guardrails.
    guard = guardrails.apply_guardrails(product, analysis, preferences)

    # Step 6: explanation (LLM with template fallback).
    context = {
        "product": product,
        "analysis": analysis,
        "guardrails": guard,
        "preferences": preferences,
    }
    explanation = _explain_with_llm(context) if _llm_available() else None
    explanation_source = "llm"
    if explanation is None:
        explanation = _explain_with_template(context)
        explanation_source = "template"

    result = {
        "status": "ok",
        "query": query,
        "product": product,
        "analysis": analysis,
        "guardrails": guard,
        "preferences": preferences,
        "explanation": explanation,
        "explanation_source": explanation_source,
    }

    # Step 7: log the run.
    log_run({
        "user_id": user_id,
        "query": query,
        "status": "ok",
        "product_name": product["product_name"],
        "source": product["source"],
        "risk_score": analysis["risk"]["score"],
        "risk_band": analysis["risk"]["band"],
        "recommendation": guard["recommendation"],
        "explanation_source": explanation_source,
        "n_conflicts": len(guard["conflicts"]),
    })

    return result
